package com.runner.app.data

/**
 * Доступность функций, которые ещё не готовы к использованию.
 *
 * Флаги в одном месте, а не в UI: если режим выключается, выключать его надо
 * и в кнопке, и в настройках, и в исполнении инструментов. Иначе остаётся
 * путь, по которому функция всё-таки сработает.
 */
object DevStatus {

    /**
     * Live-режим (управление чужим экраном).
     *
     * Выключен: управление чужим экраном работает нестабильно, а ошибка здесь
     * стоит дорого (реальные нажатия в реальных приложениях). Пока false,
     * включить режим нельзя ниоткуда: ни кнопкой в шапке, ни сохранённой
     * настройкой от прежней версии.
     */
    const val LIVE_MODE_AVAILABLE = false

    /**
     * Плавающий ассистент (OverlayActivity, плитка, ACTION_ASSIST).
     *
     * Доступен, но помечен как бета: при первом открытии показывается
     * предупреждение, что возможны сбои.
     */
    const val ASSISTANT_BETA = true
}
