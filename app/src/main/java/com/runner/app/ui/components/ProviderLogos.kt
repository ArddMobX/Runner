    /**
     * Подбор логотипа по названию модели и провайдера.
     *
     * Сначала проверяется ID модели (актуально для хабов вроде OpenRouter или Groq,
     * где через один эндпоинт запускаются модели Anthropic, Meta, DeepSeek, Google и т.д.).
     * Если по модели провайдер не определён — берётся логотип провайдера.
     */
    fun forModelOrProvider(
        modelId: String,
        providerId: String = "",
        providerName: String = ""
    ): ImageVector? {
        val modelKey = modelId.lowercase()
        return when {
            // Модели семейств
            modelKey.contains("gemini") || modelKey.contains("gemma") -> Gemini
            modelKey.contains("gpt") || modelKey.contains("o1") || modelKey.contains("o3") ||
                    modelKey.contains("chatgpt") || modelKey.contains("openai") -> OpenAI
            modelKey.contains("claude") || modelKey.contains("anthropic") -> Claude
            modelKey.contains("deepseek") -> DeepSeek
            modelKey.contains("llama") || modelKey.contains("meta") -> Meta
            modelKey.contains("mistral") || modelKey.contains("mixtral") ||
                    modelKey.contains("codestral") || modelKey.contains("pixtral") -> Mistral
            modelKey.contains("qwen") || modelKey.contains("qwq") -> Qwen
            modelKey.contains("sonar") || modelKey.contains("perplexity") -> Perplexity
            modelKey.contains("groq") -> Groq
            // Если по модели не определено — смотрим провайдера
            else -> forProvider(providerId, providerName)
        }
    }

    /**
     * Логотип по провайдеру (по ID или имени).
     */
    fun forProvider(providerId: String, providerName: String = ""): ImageVector? {
        val key = "$providerId $providerName".lowercase()
        return when {
            key.contains("openai") || key.contains("chatgpt") -> OpenAI
            key.contains("anthropic") || key.contains("claude") -> Claude
            key.contains("gemini") || key.contains("google") -> Gemini
            key.contains("deepseek") -> DeepSeek
            key.contains("groq") -> Groq
            key.contains("openrouter") -> OpenRouter
            key.contains("mistral") -> Mistral
            key.contains("meta") || key.contains("llama") -> Meta
            key.contains("perplexity") -> Perplexity
            key.contains("qwen") || key.contains("alibaba") -> Qwen
            else -> null
        }
    }

